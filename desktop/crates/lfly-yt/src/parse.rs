/// An artist page from a `browse` response for a `UC...` id.
pub fn artist_page(root: &Value) -> Option<ArtistPage> {
    let header = collect(root, "musicImmersiveHeaderRenderer")
        .into_iter()
        .next()
        .or_else(|| collect(root, "musicVisualHeaderRenderer").into_iter().next())?;
    let name = runs_text(obj(header, "title")).trim().to_string();
    if name.is_empty() {
        return None;
    }
    let header_value = Value::Object(header.clone());
    let browse_id = json::collect_strings(&header_value, "browseId")
        .into_iter()
        .find(|b| b.starts_with("UC"))
        .or_else(|| json::collect_strings(root, "browseId").into_iter().find(|b| b.starts_with("UC")));
    let listeners = runs_text(obj(header, "monthlyListenerCount")).trim().to_string();
    let subscribers = collect_in(header, "subscribeButtonRenderer")
        .first()
        .map(|s| runs_text(obj(s, "subscriberCountText")).trim().to_string())
        .unwrap_or_default();
    let subtitle = if listeners.is_empty() { subscribers.clone() } else { listeners.clone() };
    let artist = ArtistSummary {
        channel_id: browse_id.clone().filter(|b| b.starts_with("UC")),
        browse_id: browse_id.clone(),
        name,
        thumbnail_url: json::thumbnail(header),
        subtitle: some_nonblank(subtitle),
    };

    let shelves = collect(root, "musicShelfRenderer");
    let song_shelf = shelves.iter().find(|s| runs_text(obj(s, "title")).to_lowercase().contains("song")).copied();
    let top_songs = match song_shelf {
        Some(s) => shelf_tracks(s),
        None => shelves.iter().map(|s| shelf_tracks(s)).find(|t| !t.is_empty()).unwrap_or_default(),
    };
    let songs_endpoint = song_shelf
        .or_else(|| shelves.first().copied())
        .and_then(|s| path(s, &["bottomEndpoint", "browseEndpoint"]));
    let songs_browse_id = songs_endpoint.and_then(|b| string(b, "browseId")).filter(|s| !s.is_empty());
    let songs_params = songs_endpoint.and_then(|b| string(b, "params")).filter(|s| !s.is_empty());

    let carousels = collect(root, "musicCarouselShelfRenderer");
    let albums = artist_albums(&carousels, |t| t.contains("album") && !t.contains("featured"));
    let singles = artist_albums(&carousels, |t| t.contains("single") || t.contains("ep"));

    let mut videos = Vec::new();
    let mut seen_videos = HashSet::new();
    let mut playlists = Vec::new();
    let mut seen_playlists = HashSet::new();
    let mut related = Vec::new();
    let mut seen_related = HashSet::new();
    for carousel in &carousels {
        let title = carousel_title(carousel).to_lowercase();
        for item in collect_in(carousel, "musicTwoRowItemRenderer") {
            if title.contains("video") {
                if let Some(t) = video_from_two_row(item) {
                    if seen_videos.insert(t.id.clone()) {
                        videos.push(t);
                    }
                }
            }
            if let Some(p) = playlist_from_two_row(item) {
                if seen_playlists.insert(p.playlist_id.clone().unwrap_or_default()) {
                    playlists.push(p);
                }
            }
            if let Some(a) = artist_from_two_row(item) {
                if a.browse_id != browse_id && seen_related.insert(a.browse_id.clone().unwrap_or_default()) {
                    related.push(a);
                }
            }
        }
    }
    videos.truncate(50);
    playlists.truncate(50);

    Some(ArtistPage {
        artist,
        banner_url: json::raw_thumbnail(header),
        subscribers: some_nonblank(subscribers),
        monthly_audience: some_nonblank(listeners),
        description: description_of(root, Some(header)),
        top_songs,
        albums,
        singles,
        videos,
        playlists,
        related,
        songs_browse_id,
        songs_params,
    })
}

fn artist_albums(carousels: &[&Obj], wanted: impl Fn(&str) -> bool) -> Vec<AlbumSummary> {
    let mut out = Vec::new();
    let mut seen = HashSet::new();
    for carousel in carousels {
        if !wanted(&carousel_title(carousel).to_lowercase()) {
            continue;
        }
        for item in collect_in(carousel, "musicTwoRowItemRenderer") {
            let Some(album) = album_from_two_row(item, false) else { continue };
            if album.browse_id.as_deref().is_some_and(|b| !b.starts_with("MPRE")) {
                continue;
            }
            let key = album
                .browse_id
                .clone()
                .unwrap_or_else(|| format!("{}|{}", normalized_name_key(&album.title), album.year.clone().unwrap_or_default()));
            if seen.insert(key) {
                // The artist page cards show "Album • 2013", never the artist.
                out.push(AlbumSummary { artist: None, ..album });
            }
        }
    }
    out.truncate(50);
    out
}

