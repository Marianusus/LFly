/// Description text from a header or a `musicDescriptionShelfRenderer`.
fn description_of(root: &Value, header: Option<&Obj>) -> Option<String> {
    let from_header = header.and_then(|h| {
        obj(h, "description").and_then(|d| {
            let direct = runs_text(Some(d));
            if !direct.trim().is_empty() {
                return Some(direct);
            }
            obj(d, "musicDescriptionShelfRenderer").map(|m| runs_text(obj(m, "description")))
        })
    });
    from_header
        .filter(|d| !d.trim().is_empty())
        .or_else(|| {
            collect(root, "musicDescriptionShelfRenderer")
                .into_iter()
                .map(|m| runs_text(obj(m, "description")))
                .find(|d| !d.trim().is_empty())
        })
        .map(|d| d.trim().to_string())
}

fn header_of<'a>(root: &'a Value, names: &[&str]) -> Option<&'a Obj> {
    names.iter().find_map(|n| collect(root, n).into_iter().next())
}

/// An album page from a `browse` response for an `MPRE...` id.
/// `requested_id` is the id that was asked for; it wins over ids found in the page.
pub fn album_page(root: &Value, requested_id: Option<&str>) -> Option<AlbumPage> {
    let header = header_of(root, &["musicDetailHeaderRenderer", "musicResponsiveHeaderRenderer"])?;
    let title = runs_text(obj(header, "title")).trim().to_string();
    if title.is_empty() {
        return None;
    }
    let subtitle = runs_text(obj(header, "subtitle"));
    let strapline_obj = obj(header, "straplineTextOne");
    let strapline = runs_text(strapline_obj);
    let mut lines: Vec<String> = Vec::new();
    for l in [&strapline, &subtitle] {
        if !l.trim().is_empty() && !lines.contains(l) {
            lines.push(l.clone());
        }
    }
    let header_line = lines.join(" • ");
    let segments = split_segments(&header_line);
    let artist = some_nonblank(strapline.clone()).or_else(|| first_meaningful_segment(&segments));
    let year = first_year(&header_line);
    let kind = segments.iter().find(|s| s.chars().any(char::is_alphabetic) && !is_year_token(s) && is_kind_word(s)).cloned();
    let track_count = parse_track_count(&runs_text(obj(header, "secondSubtitle")));
    let header_value = Value::Object(header.clone());
    let browse_id = requested_id
        .filter(|r| r.starts_with("MPRE"))
        .map(str::to_string)
        .or_else(|| json::collect_strings(&header_value, "browseId").into_iter().find(|b| b.starts_with("MPRE")))
        .or_else(|| json::collect_strings(root, "browseId").into_iter().find(|b| b.starts_with("MPRE")));
    let all_playlists = json::collect_strings(root, "playlistId");
    let playlist_id = all_playlists.iter().find(|p| p.starts_with("OLAK")).or(all_playlists.first()).cloned();
    let cover = json::thumbnail(header);
    let release_year: Option<i32> = year.as_deref().and_then(|y| y.parse().ok());
    let header_credits = credits::from_runs(strapline_obj);
    let album = AlbumSummary {
        browse_id: browse_id.clone(),
        playlist_id,
        title: title.clone(),
        artist: artist.clone(),
        artist_id: credits::first_artist_id(&header_credits),
        year,
        thumbnail_url: cover.clone(),
        release_year,
        track_count,
        kind,
    };

    let fallback_artist = artist
        .clone()
        .filter(|a| !is_generic_artist(a))
        .or_else(|| artist_from_video_title(&title))
        .unwrap_or_default();
    // Header credits keep the artist ids ("Daft Punk" -> UC...).
    let mut fallback_credits = header_credits;
    if fallback_credits.is_empty() {
        fallback_credits = credits::from_text(Some(&fallback_artist));
    }
    let first_shelf = collect(root, "musicShelfRenderer").into_iter().map(shelf_tracks).find(|t| !t.is_empty());
    let tracks = first_shelf
        .unwrap_or_default()
        .into_iter()
        .map(|mut t| {
            if is_generic_artist(&t.artist) {
                t.artist = fallback_artist.clone();
            }
            let credits_now = match t.artists.take().filter(|a| !a.is_empty()) {
                Some(a) => a,
                None if t.artist == fallback_artist => fallback_credits.clone(),
                None => credits::from_text(Some(&t.artist)),
            };
            if t.album.is_none() {
                t.album = Some(title.clone());
            }
            if t.cover_url.is_none() {
                t.cover_url = cover.clone();
            }
            if t.release_year.is_none() {
                t.release_year = release_year;
            }
            if t.album_id.is_none() {
                t.album_id = browse_id.clone();
            }
            if t.artist_id.is_none() {
                t.artist_id = credits::first_artist_id(&credits_now).or_else(|| credits::first_artist_id(&fallback_credits));
            }
            t.artists = (!credits_now.is_empty()).then_some(credits_now);
            t
        })
        .collect();
    Some(AlbumPage { album, description: description_of(root, Some(header)), tracks })
}

/// A playlist page (first page of tracks) plus the token for more tracks.
pub fn playlist_page(root: &Value, requested_id: Option<&str>) -> Option<(PlaylistPage, Option<String>)> {
    let header = collect(root, "musicDetailHeaderRenderer")
        .into_iter()
        .next()
        .or_else(|| {
            collect(root, "musicEditablePlaylistDetailHeaderRenderer")
                .into_iter()
                .find_map(|h| collect_in(h, "musicDetailHeaderRenderer").into_iter().next())
        })
        .or_else(|| collect(root, "musicResponsiveHeaderRenderer").into_iter().next())?;
    let title = runs_text(obj(header, "title")).trim().to_string();
    if title.is_empty() {
        return None;
    }
    let subtitle = runs_text(obj(header, "subtitle"));
    let strapline = runs_text(obj(header, "straplineTextOne"));
    let segments = split_segments(if subtitle.trim().is_empty() { &strapline } else { &subtitle });
    let facepile = path(header, &["facepile", "avatarStackViewModel", "text"]).and_then(|t| string(t, "content"));
    let author = some_nonblank(strapline.clone()).or(facepile).or_else(|| first_meaningful_segment(&segments));
    let track_count = parse_track_count(&runs_text(obj(header, "secondSubtitle")));

    let shelf = collect(root, "musicPlaylistShelfRenderer").into_iter().next();
    let requested_pid = requested_id.map(|r| r.strip_prefix("VL").unwrap_or(r).to_string()).filter(|r| !r.is_empty());
    let playlist_id = shelf
        .and_then(|s| string(s, "playlistId"))
        .or(requested_pid)
        .or_else(|| json::collect_strings(root, "playlistId").into_iter().next());
    let browse_id = playlist_id.as_ref().map(|p| format!("VL{p}"));
    let playlist = PlaylistSummary {
        playlist_id,
        browse_id,
        title,
        author,
        track_count,
        thumbnail_url: json::thumbnail(header),
    };
    let (tracks, continuation) = match shelf {
        Some(s) => {
            let value = Value::Object(s.clone());
            (shelf_tracks(s), continuation_token(&value))
        }
        None => {
            let first = collect(root, "musicShelfRenderer").into_iter().map(shelf_tracks).find(|t| !t.is_empty());
            (first.unwrap_or_default(), None)
        }
    };
    Some((PlaylistPage { playlist, description: description_of(root, Some(header)), tracks }, continuation))
}

/// A continuation page of a playlist or song list. Continuation responses carry
/// the rows directly (no shelf), so every list row is read.
pub fn tracks_page(root: &Value) -> TracksPage {
    let shelf = collect(root, "musicPlaylistShelfRenderer").into_iter().next();
    let tracks = match shelf {
        Some(s) => shelf_tracks(s),
        None => tracks_in(root),
    };
    TracksPage { tracks, continuation: continuation_token(root) }
}

