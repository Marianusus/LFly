use std::sync::LazyLock;

static VIDEO_ID_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^[A-Za-z0-9_-]{11}$").unwrap());
static DURATION_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^(\d{1,2}:)?\d{1,2}:\d{2}$").unwrap());
static STREAM_COUNT_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?i)(\d[\d.,]*)\s*([KMB])?\s*(plays|views)").unwrap());
static YEAR_TOKEN_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"^\d{4}$").unwrap());
static FIRST_YEAR_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\b(\d{4})\b").unwrap());
static TRACK_COUNT_RE: LazyLock<Regex> =
    LazyLock::new(|| Regex::new(r"(?i)(\d+)\s*(brano|brani|track|tracks|song|songs)").unwrap());
static ARTIST_WORD_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\bartist\b").unwrap());
static ALBUM_WORD_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\balbum\b|\bsingle\b|\bep\b").unwrap());
static PLAYLIST_WORD_RE: LazyLock<Regex> = LazyLock::new(|| Regex::new(r"\bplaylist\b").unwrap());

const KIND_WORDS: &[&str] = &[
    "song", "songs", "video", "videos", "album", "albums", "single", "singles", "ep", "eps", "playlist",
    "playlists", "artist", "artists",
];

/// True for an 11-character YouTube video id.
pub fn is_valid_video_id(id: &str) -> bool {
    VIDEO_ID_RE.is_match(id)
}

/// True for YouTube's generic channel labels, which are not a usable artist.
pub fn is_generic_artist(value: &str) -> bool {
    let n = value.trim().to_lowercase();
    n.is_empty()
        || n == "youtube"
        || n == "youtube music"
        || n == "youtube music - topic"
        || n == "auto-generated by youtube"
}

/// "3.6B plays" / "20M views" as an absolute count.
pub fn parse_stream_count(text: &str) -> Option<i64> {
    let caps = STREAM_COUNT_RE.captures(text)?;
    let value: f64 = caps[1].replace(',', "").parse().ok()?;
    let multiplier = match caps.get(2).map(|m| m.as_str().to_ascii_uppercase()).as_deref() {
        Some("K") => 1_000.0,
        Some("M") => 1_000_000.0,
        Some("B") => 1_000_000_000.0,
        _ => 1.0,
    };
    Some((value * multiplier) as i64)
}

/// "3:45" or "1:02:15" in milliseconds; 0 when unreadable.
pub fn parse_duration_ms(text: &str) -> i64 {
    let parts: Vec<i64> = match text.trim().split(':').map(|p| p.trim().parse::<i64>()).collect() {
        Ok(p) => p,
        Err(_) => return 0,
    };
    match parts.as_slice() {
        [m, s] => (m * 60 + s) * 1000,
        [h, m, s] => (h * 3600 + m * 60 + s) * 1000,
        _ => 0,
    }
}

fn is_duration(text: &str) -> bool {
    DURATION_RE.is_match(text)
}

fn is_kind_label(value: &str) -> bool {
    matches!(
        value.trim().to_lowercase().as_str(),
        "song" | "songs" | "video" | "videos" | "album" | "albums" | "single" | "singles" | "ep" | "eps" | "playlist" | "playlists"
    )
}

fn is_kind_word(value: &str) -> bool {
    KIND_WORDS.contains(&value.trim().to_lowercase().as_str())
}

fn is_year_token(value: &str) -> bool {
    YEAR_TOKEN_RE.is_match(value.trim())
}

fn first_year(value: &str) -> Option<String> {
    FIRST_YEAR_RE.captures(value).map(|c| c[1].to_string())
}

fn parse_track_count(value: &str) -> Option<i32> {
    TRACK_COUNT_RE.captures(value)?[1].parse().ok()
}

fn normalized_name_key(value: &str) -> String {
    value.to_lowercase().chars().filter(|c| c.is_ascii_lowercase() || c.is_ascii_digit()).collect()
}

fn first_meaningful_segment(segments: &[String]) -> Option<String> {
    segments
        .iter()
        .find(|s| !s.trim().is_empty() && !is_kind_word(s) && !is_year_token(s))
        .cloned()
}

fn split_segments(text: &str) -> Vec<String> {
    text.split('•').map(|s| s.trim().to_string()).filter(|s| !s.is_empty()).collect()
}

fn artist_from_video_title(title: &str) -> Option<String> {
    let (left, _) = title.split_once(" - ")?;
    let left = left.trim();
    (!left.is_empty() && !is_generic_artist(left)).then(|| left.to_string())
}

fn some_nonblank(s: String) -> Option<String> {
    (!s.trim().is_empty()).then_some(s)
}

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Kind {
    Artist,
    Album,
    Playlist,
    Unknown,
}

fn classify_page_type(pt: &str) -> Kind {
    match pt {
        "MUSIC_PAGE_TYPE_ARTIST" => Kind::Artist,
        "MUSIC_PAGE_TYPE_ALBUM" => Kind::Album,
        "MUSIC_PAGE_TYPE_PLAYLIST" => Kind::Playlist,
        _ => Kind::Unknown,
    }
}

fn classify_browse_id(browse_id: Option<&str>) -> Kind {
    let id = browse_id.unwrap_or("").trim();
    if id.starts_with("VL") || id.starts_with("RD") {
        Kind::Playlist
    } else if id.starts_with("MPRE") {
        Kind::Album
    } else if id.starts_with("UC") {
        Kind::Artist
    } else {
        Kind::Unknown
    }
}

fn classify_subtitle(subtitle: &str) -> Kind {
    let s = subtitle.to_lowercase();
    if ARTIST_WORD_RE.is_match(&s) {
        Kind::Artist
    } else if ALBUM_WORD_RE.is_match(&s) {
        Kind::Album
    } else if PLAYLIST_WORD_RE.is_match(&s) {
        Kind::Playlist
    } else {
        Kind::Unknown
    }
}

/// A present page type wins (so podcasts and user channels stay unknown), then
/// the id prefix, then words in the subtitle.
fn classify_entity(page_type: Option<&str>, browse_id: Option<&str>, subtitle: &str) -> Kind {
    if let Some(pt) = page_type {
        return classify_page_type(pt);
    }
    match classify_browse_id(browse_id) {
        Kind::Unknown => classify_subtitle(subtitle),
        k => k,
    }
}

// --- list item helpers -------------------------------------------------------------------------

fn flex_text(item: &Obj, index: usize) -> Option<&Obj> {
    let col = arr(item, "flexColumns")?.get(index)?.as_object()?;
    path(col, &["musicResponsiveListItemFlexColumnRenderer", "text"])
}

fn subtitle_segments(item: &Obj) -> Vec<String> {
    flex_text(item, 1).map(|t| split_segments(&runs_text(Some(t)))).unwrap_or_default()
}

fn subtitle_flat(item: &Obj) -> String {
    let Some(t) = flex_text(item, 1) else { return String::new() };
    runs_text(Some(t)).replace('•', " ").split_whitespace().collect::<Vec<_>>().join(" ")
}

fn first_duration_text(text: Option<&Obj>) -> Option<String> {
    let text = text?;
    if let Some(s) = string(text, "simpleText") {
        let s = s.trim();
        if is_duration(s) {
            return Some(s.to_string());
        }
    }
    json::runs(Some(text)).find_map(|r| {
        let s = string(r, "text")?;
        let s = s.trim();
        is_duration(s).then(|| s.to_string())
    })
}

fn extract_duration_ms(item: &Obj) -> i64 {
    if let Some(cols) = arr(item, "flexColumns") {
        for col in cols.iter().filter_map(Value::as_object) {
            if let Some(d) = first_duration_text(path(col, &["musicResponsiveListItemFlexColumnRenderer", "text"])) {
                return parse_duration_ms(&d);
            }
        }
    }
    if let Some(cols) = arr(item, "fixedColumns") {
        for col in cols.iter().filter_map(Value::as_object) {
            if let Some(d) = first_duration_text(path(col, &["musicResponsiveListItemFixedColumnRenderer", "text"])) {
                return parse_duration_ms(&d);
            }
        }
    }
    first_duration_text(obj(item, "lengthText")).map(|d| parse_duration_ms(&d)).unwrap_or(0)
}

fn extract_stream_count(item: &Obj) -> Option<i64> {
    for col in arr(item, "flexColumns")?.iter().filter_map(Value::as_object) {
        let text = path(col, &["musicResponsiveListItemFlexColumnRenderer", "text"]);
        for run in json::runs(text) {
            if let Some(n) = string(run, "text").and_then(|t| parse_stream_count(&t)) {
                return Some(n);
            }
        }
    }
    None
}

/// `(title, browseId)` of the first run that really points at an album.
fn album_from_runs(text: Option<&Obj>) -> (Option<String>, Option<String>) {
    for run in json::runs(text) {
        let Some(browse) = path(run, &["navigationEndpoint", "browseEndpoint"]) else { continue };
        let browse_id = string(browse, "browseId");
        let is_album = json::page_type(Some(browse)).as_deref() == Some("MUSIC_PAGE_TYPE_ALBUM")
            || browse_id.as_deref().is_some_and(|b| b.starts_with("MPRE"));
        if !is_album {
            continue;
        }
        let title = string(run, "text").map(|t| t.trim().to_string()).filter(|t| !t.is_empty());
        return (title, browse_id);
    }
    (None, None)
}

/// Builds credits + display artist from a byline, falling back to text and then
/// to the "Artist - Title" pattern of the video title.
fn byline_artists(byline: Option<&Obj>, fallback_text: Option<&str>, title: &str) -> (Vec<ArtistCredit>, String) {
    let mut artists: Vec<ArtistCredit> =
        credits::from_runs(byline).into_iter().filter(|c| !is_generic_artist(&c.name)).collect();
    if artists.is_empty() {
        artists = credits::from_text(fallback_text).into_iter().filter(|c| !is_generic_artist(&c.name)).collect();
    }
    let mut artist = credits::display_name(&artists);
    if artist.trim().is_empty() {
        artist = artist_from_video_title(title).unwrap_or_default();
        if !artist.is_empty() {
            artists = credits::from_text(Some(&artist));
        }
    }
    (artists, artist)
}

/// One `musicResponsiveListItemRenderer` row as a playable track.
pub(crate) fn track_from_item(item: &Obj) -> Option<Track> {
    let flex = arr(item, "flexColumns")?;
    if flex.is_empty() {
        return None;
    }
    let col0 = flex_text(item, 0);
    let title = runs_text(col0).trim().to_string();
    if title.is_empty() {
        return None;
    }
    let video_id = json::run_video_id(col0)
        .or_else(|| obj(item, "playlistItemData").and_then(|p| string(p, "videoId")))
        .or_else(|| {
            path(
                item,
                &["overlay", "musicItemThumbnailOverlayRenderer", "content", "musicPlayButtonRenderer", "playNavigationEndpoint", "watchEndpoint"],
            )
            .and_then(|w| string(w, "videoId"))
        })
        .filter(|v| !v.trim().is_empty())?;

    let mut artists: Vec<ArtistCredit> = Vec::new();
    let mut artist = String::new();
    let mut album = None;
    let mut album_id = None;
    let mut duration_ms = 0;
    let mut is_video = false;

    if let Some(col1) = flex_text(item, 1) {
        let mut parts: Vec<String> = json::runs(Some(col1))
            .filter_map(|r| string(r, "text"))
            .map(|t| t.trim().to_string())
            .filter(|t| !t.is_empty() && t != "•")
            .collect();
        if !parts.is_empty() {
            if let Some(pos) = parts.iter().position(|p| is_duration(p)) {
                duration_ms = parse_duration_ms(&parts[pos]);
                parts.remove(pos);
            }
            if parts.first().is_some_and(|p| p.eq_ignore_ascii_case("video")) {
                is_video = true;
            }
            let (album_title, album_browse) = album_from_runs(Some(col1));
            album_id = album_browse;
            let artist_part = parts
                .iter()
                .filter(|p| {
                    !is_duration(p)
                        && !is_kind_label(p)
                        && parse_stream_count(p).is_none()
                        && !p.eq_ignore_ascii_case("youtube")
                        && !is_generic_artist(p)
                })
                .find(|p| Some(p.as_str()) != album_title.as_deref())
                .cloned();
            (artists, artist) = byline_artists(Some(col1), artist_part.as_deref(), &title);
            if let Some(a) = album_title {
                if !a.eq_ignore_ascii_case(&title) && !a.eq_ignore_ascii_case(&artist) {
                    album = Some(a);
                }
            }
        }
    }
    if duration_ms <= 0 {
        duration_ms = extract_duration_ms(item);
    }

    Some(Track {
        id: format!("yt_{video_id}"),
        title,
        artist,
        album,
        duration_ms,
        cover_url: json::thumbnail(item),
        provider: "YouTube".to_string(),
        streams: extract_stream_count(item),
        is_video,
        album_id,
        artist_id: credits::first_artist_id(&artists),
        artists: (!artists.is_empty()).then_some(artists),
        ..Track::default()
    })
}

fn tracks_in(root: &Value) -> Vec<Track> {
    collect(root, "musicResponsiveListItemRenderer").into_iter().filter_map(track_from_item).collect()
}

fn tracks_in_obj(root: &Obj) -> Vec<Track> {
    collect_in(root, "musicResponsiveListItemRenderer").into_iter().filter_map(track_from_item).collect()
}

