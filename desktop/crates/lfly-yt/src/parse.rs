/// Song and video rows of a search page.
pub fn search_tracks(root: &Value) -> Vec<Track> {
    tracks_in(root).into_iter().filter(|t| !is_generic_artist(&t.artist)).collect()
}

/// Typeahead strings from `get_search_suggestions`.
pub fn search_suggestions(root: &Value) -> Vec<String> {
    let mut out: Vec<String> = Vec::new();
    for r in collect(root, "searchSuggestionRenderer") {
        let from_endpoint = path(r, &["navigationEndpoint", "searchEndpoint"]).and_then(|s| string(s, "query"));
        let from_runs = obj(r, "suggestion").map(|s| runs_text(Some(s)));
        if let Some(q) = from_endpoint.or(from_runs).map(|q| q.trim().to_string()).filter(|q| !q.is_empty()) {
            if !out.contains(&q) {
                out.push(q);
            }
        }
    }
    out
}

/// Token for the next page of a search or browse response. Only real
/// continuation holders are read, so a stray "token" field is never followed.
pub fn continuation_token(root: &Value) -> Option<String> {
    for c in collect(root, "continuationItemRenderer") {
        if let Some(t) = path(c, &["continuationEndpoint", "continuationCommand"]).and_then(|cc| string(cc, "token")) {
            return Some(t);
        }
    }
    for c in collect(root, "nextContinuationData") {
        if let Some(t) = string(c, "continuation") {
            return Some(t);
        }
    }
    None
}

fn normalized_artists_key(track: &Track) -> String {
    let mut names: Vec<String> = track
        .artists
        .iter()
        .flatten()
        .map(|c| credits::normalize(&c.name))
        .filter(|n| !n.is_empty())
        .collect();
    names.sort();
    let joined = names.join("|");
    if joined.is_empty() {
        credits::normalize(&track.artist)
    } else {
        joined
    }
}

/// Merges the general search ranking with the song-filtered one, like the phone:
/// general order first (videos stay), enriched with the song version of the same
/// video; song-only rows appended. Duplicate recordings are dropped.
pub fn merge_search_results(general: Vec<Track>, songs: Vec<Track>, limit: usize) -> Vec<Track> {
    let mut out: Vec<Track> = Vec::new();
    let mut seen_ids = HashSet::new();
    let mut seen_keys: Vec<(String, String, i64)> = Vec::new();
    let mut add = |t: Track, out: &mut Vec<Track>| {
        if out.len() >= limit || !seen_ids.insert(t.id.clone()) {
            return;
        }
        let key = (credits::normalize(&t.title), normalized_artists_key(&t), t.duration_ms.max(0));
        let duplicate = !key.0.is_empty()
            && seen_keys.iter().any(|s| s.0 == key.0 && s.1 == key.1 && (s.2 == key.2 || s.2 == 0 || key.2 == 0));
        if duplicate {
            return;
        }
        seen_keys.push(key);
        out.push(t);
    };
    for mut item in general {
        if let Some(rich) = songs.iter().find(|s| s.id == item.id) {
            if item.album.is_none() {
                item.album = rich.album.clone();
            }
            if item.duration_ms <= 0 {
                item.duration_ms = rich.duration_ms;
            }
            if item.cover_url.is_none() {
                item.cover_url = rich.cover_url.clone();
            }
            if item.artist_id.is_none() {
                item.artist_id = rich.artist_id.clone();
            }
            if item.artists.as_ref().is_none_or(|a| a.is_empty()) {
                item.artists = rich.artists.clone();
            }
        }
        add(item, &mut out);
    }
    for s in songs {
        add(s, &mut out);
    }
    out
}

/// Artist rows and cards of a search page.
pub fn search_artists(root: &Value, limit: usize) -> Vec<ArtistSummary> {
    let mut out = Vec::new();
    if limit == 0 {
        return out;
    }
    let mut seen_ids = HashSet::new();
    let mut seen_names = HashSet::new();

    // 1. The top result card, only when its title opens an artist page.
    for card in collect(root, "musicCardShelfRenderer") {
        if out.len() >= limit {
            break;
        }
        let title_obj = obj(card, "title");
        let name = runs_text(title_obj).trim().to_string();
        if name.is_empty() {
            continue;
        }
        let subtitle = runs_text(obj(card, "subtitle")).trim().to_string();
        let title_browse = json::first_browse_endpoint(title_obj);
        let item_browse = path(card, &["navigationEndpoint", "browseEndpoint"]);
        let Some(browse) = title_browse.or(item_browse) else { continue };
        let browse_id = string(browse, "browseId");
        let title_is_artist = json::page_type(title_browse).as_deref() == Some("MUSIC_PAGE_TYPE_ARTIST")
            || browse_id.as_deref().is_some_and(|b| b.starts_with("UC"));
        let kind = classify_entity(json::page_type(Some(browse)).as_deref(), browse_id.as_deref(), &subtitle);
        if kind != Kind::Artist || !title_is_artist {
            continue;
        }
        let channel_id = json::run_channel_id(title_obj).or_else(|| browse_id.clone().filter(|b| b.starts_with("UC")));
        if let Some(b) = browse_id.as_deref().filter(|b| !b.is_empty()) {
            if !seen_ids.insert(b.to_string()) {
                continue;
            }
        }
        let key = normalized_name_key(&name);
        if !key.is_empty() {
            seen_names.insert(key);
        }
        out.push(ArtistSummary { browse_id, channel_id, name, thumbnail_url: json::thumbnail(card), subtitle: some_nonblank(subtitle) });
    }

    // 2. List rows.
    for item in collect(root, "musicResponsiveListItemRenderer") {
        if out.len() >= limit {
            break;
        }
        let Some(col0) = flex_text(item, 0) else { continue };
        let title = runs_text(Some(col0)).trim().to_string();
        if title.is_empty() {
            continue;
        }
        let subtitle = subtitle_flat(item);
        let col_browse = json::first_browse_endpoint(Some(col0));
        let item_browse = path(item, &["navigationEndpoint", "browseEndpoint"]);
        let browse_id = col_browse.or(item_browse).and_then(|b| string(b, "browseId"));
        let pt = json::page_type(item_browse).or_else(|| json::page_type(col_browse));
        if classify_entity(pt.as_deref(), browse_id.as_deref(), &subtitle) != Kind::Artist {
            continue;
        }
        let channel_id = json::run_channel_id(Some(col0)).or_else(|| {
            browse_id
                .clone()
                .filter(|_| json::page_type(item_browse).as_deref() == Some("MUSIC_PAGE_TYPE_ARTIST"))
        });
        if let Some(b) = browse_id.as_deref().filter(|b| !b.is_empty()) {
            if !seen_ids.insert(b.to_string()) {
                continue;
            }
        }
        let key = normalized_name_key(&title);
        if !key.is_empty() && !seen_names.insert(key) {
            continue;
        }
        out.push(ArtistSummary { browse_id, channel_id, name: title, thumbnail_url: json::thumbnail(item), subtitle: some_nonblank(subtitle) });
    }

    // 3. Artist carousels.
    for carousel in collect(root, "musicCarouselShelfRenderer") {
        for item in collect_in(carousel, "musicTwoRowItemRenderer") {
            if out.len() >= limit {
                return out;
            }
            if let Some(a) = artist_from_two_row(item) {
                let id = a.browse_id.clone().unwrap_or_default();
                if !seen_ids.insert(id) {
                    continue;
                }
                let key = normalized_name_key(&a.name);
                if !key.is_empty() && !seen_names.insert(key) {
                    continue;
                }
                out.push(a);
            }
        }
    }
    out
}

fn artist_from_two_row(item: &Obj) -> Option<ArtistSummary> {
    let title = runs_text(obj(item, "title")).trim().to_string();
    if title.is_empty() {
        return None;
    }
    let browse_id = path(item, &["navigationEndpoint", "browseEndpoint"]).and_then(|b| string(b, "browseId"))?;
    if !browse_id.starts_with("UC") {
        return None;
    }
    let subtitle = runs_text(obj(item, "subtitle")).trim().to_string();
    Some(ArtistSummary {
        browse_id: Some(browse_id.clone()),
        channel_id: Some(browse_id),
        name: title,
        thumbnail_url: json::thumbnail(item),
        subtitle: some_nonblank(subtitle),
    })
}

/// Album rows and cards of a search page.
pub fn search_albums(root: &Value, limit: usize) -> Vec<AlbumSummary> {
    let mut out = Vec::new();
    if limit == 0 {
        return out;
    }
    let mut seen_ids = HashSet::new();
    let mut seen_keys = HashSet::new();
    for item in collect(root, "musicResponsiveListItemRenderer") {
        if out.len() >= limit {
            break;
        }
        let Some(col0) = flex_text(item, 0) else { continue };
        let title = runs_text(Some(col0)).trim().to_string();
        if title.is_empty() {
            continue;
        }
        let segments = subtitle_segments(item);
        let subtitle = segments.join(" • ");
        let col_browse = json::first_browse_endpoint(Some(col0));
        let item_browse = path(item, &["navigationEndpoint", "browseEndpoint"]);
        let browse_id = col_browse.or(item_browse).and_then(|b| string(b, "browseId"));
        let item_watch_pid = path(item, &["navigationEndpoint", "watchEndpoint"]).and_then(|w| string(w, "playlistId"));
        let playlist_id = json::run_watch_playlist_id(Some(col0)).or(item_watch_pid);
        let pt = json::page_type(item_browse).or_else(|| json::page_type(col_browse));
        if classify_entity(pt.as_deref(), browse_id.as_deref(), &subtitle) != Kind::Album {
            continue;
        }
        let artist = first_meaningful_segment(&segments);
        let year = first_year(&subtitle);
        match browse_id.clone().or_else(|| playlist_id.clone()) {
            Some(id) => {
                if !seen_ids.insert(id) {
                    continue;
                }
            }
            None => {
                let key = format!("{}|{}", normalized_name_key(&title), normalized_name_key(artist.as_deref().unwrap_or("")));
                if !seen_keys.insert(key) {
                    continue;
                }
            }
        }
        let kind = segments.first().filter(|s| is_kind_word(s)).cloned();
        out.push(AlbumSummary {
            browse_id,
            playlist_id,
            title,
            artist,
            release_year: year.as_deref().and_then(|y| y.parse().ok()),
            year,
            thumbnail_url: json::thumbnail(item),
            artist_id: credits::first_artist_id(&credits::from_runs(flex_text(item, 1))),
            kind,
            ..AlbumSummary::default()
        });
    }
    for carousel in collect(root, "musicCarouselShelfRenderer") {
        for item in collect_in(carousel, "musicTwoRowItemRenderer") {
            if out.len() >= limit {
                return out;
            }
            let Some(album) = album_from_two_row(item, true) else { continue };
            if let Some(id) = album.detail_id() {
                if !seen_ids.insert(id.to_string()) {
                    continue;
                }
            }
            out.push(album);
        }
    }
    out
}

/// A two-row album card. With `need_album_id` the card must carry an `MPRE`
/// browse id or an `OLAK` playlist id.
fn album_from_two_row(item: &Obj, need_album_id: bool) -> Option<AlbumSummary> {
    let title = runs_text(obj(item, "title")).trim().to_string();
    if title.is_empty() {
        return None;
    }
    let nav = obj(item, "navigationEndpoint");
    let browse_id = nav.and_then(|n| obj(n, "browseEndpoint")).and_then(|b| string(b, "browseId"));
    let playlist_id = nav.and_then(|n| obj(n, "watchEndpoint")).and_then(|w| string(w, "playlistId"));
    let is_album = browse_id.as_deref().is_some_and(|b| b.starts_with("MPRE"))
        || playlist_id.as_deref().is_some_and(|p| p.starts_with("OLAK"));
    if need_album_id && !is_album {
        return None;
    }
    let subtitle = runs_text(obj(item, "subtitle"));
    let year = first_year(&subtitle);
    let segments = split_segments(&subtitle);
    let kind = segments.iter().find(|s| s.chars().any(char::is_alphabetic) && !is_year_token(s)).cloned();
    let artist = segments
        .iter()
        .find(|s| s.chars().any(char::is_alphabetic) && !is_year_token(s) && !is_kind_word(s))
        .cloned();
    Some(AlbumSummary {
        browse_id,
        playlist_id,
        title,
        artist,
        release_year: year.as_deref().and_then(|y| y.parse().ok()),
        year,
        thumbnail_url: json::thumbnail(item),
        artist_id: credits::first_artist_id(&credits::from_runs(obj(item, "subtitle"))),
        kind: kind.filter(|k| is_kind_word(k)),
        ..AlbumSummary::default()
    })
}

/// Playlist rows of a search page.
pub fn search_playlists(root: &Value, limit: usize) -> Vec<PlaylistSummary> {
    let mut out = Vec::new();
    if limit == 0 {
        return out;
    }
    let mut seen_ids = HashSet::new();
    let mut seen_keys = HashSet::new();
    for item in collect(root, "musicResponsiveListItemRenderer") {
        if out.len() >= limit {
            break;
        }
        let Some(col0) = flex_text(item, 0) else { continue };
        let title = runs_text(Some(col0)).trim().to_string();
        if title.is_empty() {
            continue;
        }
        let segments = subtitle_segments(item);
        let subtitle = segments.join(" • ");
        let col_browse = json::first_browse_endpoint(Some(col0));
        let item_browse = path(item, &["navigationEndpoint", "browseEndpoint"]);
        let browse_id = col_browse.or(item_browse).and_then(|b| string(b, "browseId"));
        let item_watch_pid = path(item, &["navigationEndpoint", "watchEndpoint"]).and_then(|w| string(w, "playlistId"));
        let from_watch = json::run_watch_playlist_id(Some(col0)).or(item_watch_pid);
        let pt = json::page_type(item_browse).or_else(|| json::page_type(col_browse));
        if classify_entity(pt.as_deref(), browse_id.as_deref(), &subtitle) != Kind::Playlist {
            continue;
        }
        let author = first_meaningful_segment(&segments);
        let playlist_id = from_watch.or_else(|| {
            browse_id.as_deref().map(|b| b.strip_prefix("VL").unwrap_or(b).to_string()).filter(|p| !p.is_empty())
        });
        match playlist_id.clone().or_else(|| browse_id.clone()) {
            Some(id) => {
                if !seen_ids.insert(id) {
                    continue;
                }
            }
            None => {
                let key = format!("{}|{}", normalized_name_key(&title), normalized_name_key(author.as_deref().unwrap_or("")));
                if !seen_keys.insert(key) {
                    continue;
                }
            }
        }
        out.push(PlaylistSummary {
            playlist_id,
            browse_id,
            title,
            author,
            track_count: parse_track_count(&subtitle),
            thumbnail_url: json::thumbnail(item),
        });
    }
    out
}

/// The "Top result" card of a general search.
pub fn search_top_result(root: &Value) -> Option<MediaItem> {
    let card = collect(root, "musicCardShelfRenderer").into_iter().next()?;
    let title_obj = obj(card, "title");
    let title = runs_text(title_obj).trim().to_string();
    if title.is_empty() {
        return None;
    }
    let subtitle_obj = obj(card, "subtitle");
    let subtitle = runs_text(subtitle_obj);
    let segments = split_segments(&subtitle);
    let browse = json::first_browse_endpoint(title_obj).or_else(|| path(card, &["navigationEndpoint", "browseEndpoint"]));
    if let Some(browse) = browse {
        let browse_id = string(browse, "browseId");
        match classify_entity(json::page_type(Some(browse)).as_deref(), browse_id.as_deref(), &subtitle) {
            Kind::Artist => {
                return Some(MediaItem::Artist(ArtistSummary {
                    channel_id: browse_id.clone().filter(|b| b.starts_with("UC")),
                    browse_id,
                    name: title,
                    thumbnail_url: json::thumbnail(card),
                    subtitle: some_nonblank(subtitle.trim().to_string()),
                }))
            }
            Kind::Album => {
                let year = first_year(&subtitle);
                return Some(MediaItem::Album(AlbumSummary {
                    browse_id,
                    title,
                    artist: first_meaningful_segment(&segments),
                    release_year: year.as_deref().and_then(|y| y.parse().ok()),
                    year,
                    thumbnail_url: json::thumbnail(card),
                    artist_id: credits::first_artist_id(&credits::from_runs(subtitle_obj)),
                    kind: segments.first().filter(|s| is_kind_word(s)).cloned(),
                    ..AlbumSummary::default()
                }));
            }
            Kind::Playlist => {
                return Some(MediaItem::Playlist(PlaylistSummary {
                    playlist_id: browse_id.as_deref().map(|b| b.strip_prefix("VL").unwrap_or(b).to_string()),
                    browse_id,
                    title,
                    author: first_meaningful_segment(&segments),
                    track_count: None,
                    thumbnail_url: json::thumbnail(card),
                }));
            }
            Kind::Unknown => {}
        }
    }
    let video_id = json::run_video_id(title_obj)
        .or_else(|| path(card, &["onTap", "watchEndpoint"]).and_then(|w| string(w, "videoId")))?;
    let (artists, artist) = byline_artists(subtitle_obj, None, &title);
    let (album, album_id) = album_from_runs(subtitle_obj);
    let duration_ms = segments.iter().find(|s| is_duration(s)).map(|d| parse_duration_ms(d)).unwrap_or(0);
    Some(MediaItem::Song(Track {
        id: format!("yt_{video_id}"),
        title,
        artist,
        album,
        album_id,
        duration_ms,
        cover_url: json::thumbnail(card),
        provider: "YouTube".to_string(),
        is_video: segments.first().is_some_and(|s| s.eq_ignore_ascii_case("video")),
        streams: segments.iter().find_map(|s| parse_stream_count(s)),
        artist_id: credits::first_artist_id(&artists),
        artists: (!artists.is_empty()).then_some(artists),
        ..Track::default()
    }))
}

