/// One card of a home shelf.
fn home_item(key: &str, item: &Obj) -> Option<MediaItem> {
    match key {
        "musicResponsiveListItemRenderer" => {
            if let Some(t) = track_from_item(item) {
                return Some(MediaItem::Song(t));
            }
            let col0 = flex_text(item, 0);
            let title = runs_text(col0).trim().to_string();
            let browse = json::first_browse_endpoint(col0).or_else(|| path(item, &["navigationEndpoint", "browseEndpoint"]))?;
            entity_card(&title, browse, &runs_text(flex_text(item, 1)), json::thumbnail(item))
        }
        "musicTwoRowItemRenderer" => {
            let title = runs_text(obj(item, "title")).trim().to_string();
            if title.is_empty() {
                return None;
            }
            let nav = obj(item, "navigationEndpoint")?;
            if let Some(browse) = obj(nav, "browseEndpoint") {
                let subtitle = runs_text(obj(item, "subtitle"));
                return entity_card(&title, browse, &subtitle, json::thumbnail(item));
            }
            let video_id = obj(nav, "watchEndpoint").and_then(|w| string(w, "videoId"))?;
            let subtitle_obj = obj(item, "subtitle");
            let subtitle = runs_text(subtitle_obj);
            let segments = split_segments(&subtitle);
            let first_text = segments.iter().find(|s| !is_kind_word(s)).cloned();
            let (artists, artist) = byline_artists(subtitle_obj, first_text.as_deref(), &title);
            let (album, album_id) = album_from_runs(subtitle_obj);
            Some(MediaItem::Song(Track {
                id: format!("yt_{video_id}"),
                title,
                artist,
                album,
                album_id,
                cover_url: json::thumbnail(item),
                provider: "YouTube".to_string(),
                is_video: segments.first().is_some_and(|s| s.eq_ignore_ascii_case("video"))
                    || path(nav, &["watchEndpoint", "watchEndpointMusicSupportedConfigs", "watchEndpointMusicConfig"])
                        .and_then(|c| string(c, "musicVideoType"))
                        .is_some_and(|t| t != "MUSIC_VIDEO_TYPE_ATV"),
                streams: segments.iter().find_map(|s| parse_stream_count(s)),
                artist_id: credits::first_artist_id(&artists),
                artists: (!artists.is_empty()).then_some(artists),
                ..Track::default()
            }))
        }
        _ => None,
    }
}

fn entity_card(title: &str, browse: &Obj, subtitle: &str, thumb: Option<String>) -> Option<MediaItem> {
    if title.is_empty() {
        return None;
    }
    let browse_id = string(browse, "browseId");
    let segments = split_segments(subtitle);
    match classify_entity(json::page_type(Some(browse)).as_deref(), browse_id.as_deref(), subtitle) {
        Kind::Artist => Some(MediaItem::Artist(ArtistSummary {
            channel_id: browse_id.clone().filter(|b| b.starts_with("UC")),
            browse_id,
            name: title.to_string(),
            thumbnail_url: thumb,
            subtitle: some_nonblank(subtitle.trim().to_string()),
        })),
        Kind::Album => {
            let year = first_year(subtitle);
            Some(MediaItem::Album(AlbumSummary {
                browse_id,
                title: title.to_string(),
                artist: segments
                    .iter()
                    .find(|s| s.chars().any(char::is_alphabetic) && !is_year_token(s) && !is_kind_word(s))
                    .cloned(),
                release_year: year.as_deref().and_then(|y| y.parse().ok()),
                year,
                thumbnail_url: thumb,
                kind: segments.first().filter(|s| is_kind_word(s)).cloned(),
                ..AlbumSummary::default()
            }))
        }
        Kind::Playlist => Some(MediaItem::Playlist(PlaylistSummary {
            playlist_id: browse_id.as_deref().map(|b| b.strip_prefix("VL").unwrap_or(b).to_string()),
            browse_id,
            title: title.to_string(),
            author: first_meaningful_segment(&segments),
            track_count: parse_track_count(subtitle),
            thumbnail_url: thumb,
        })),
        Kind::Unknown => None,
    }
}

fn shelf_from_carousel(carousel: &Obj) -> Option<Shelf> {
    let header = path(carousel, &["header", "musicCarouselShelfBasicHeaderRenderer"]);
    let title = runs_text(header.and_then(|h| obj(h, "title"))).trim().to_string();
    let strapline = some_nonblank(runs_text(header.and_then(|h| obj(h, "strapline"))).trim().to_string());
    let more_browse_id = header
        .and_then(|h| path(h, &["moreContentButton", "buttonRenderer", "navigationEndpoint", "browseEndpoint"]))
        .or_else(|| header.and_then(|h| json::first_browse_endpoint(obj(h, "title"))))
        .and_then(|b| string(b, "browseId"));
    let mut items = Vec::new();
    for entry in arr(carousel, "contents").into_iter().flatten().filter_map(Value::as_object) {
        for (key, value) in entry {
            if let Some(item) = value.as_object().and_then(|v| home_item(key, v)) {
                items.push(item);
            }
        }
    }
    if title.is_empty() || items.is_empty() {
        return None;
    }
    Some(Shelf { title, strapline, more_browse_id, items })
}

/// Shelves of a `FEmusic_home` response or of one of its continuation pages.
pub fn home_page(root: &Value) -> HomePage {
    // Walk the section list in order so shelves keep YouTube's order.
    let section = collect(root, "sectionListContinuation")
        .into_iter()
        .next()
        .or_else(|| collect(root, "sectionListRenderer").into_iter().next());
    let mut shelves = Vec::new();
    if let Some(section) = section {
        for entry in arr(section, "contents").into_iter().flatten().filter_map(Value::as_object) {
            if let Some(shelf) = obj(entry, "musicCarouselShelfRenderer").and_then(shelf_from_carousel) {
                shelves.push(shelf);
            }
        }
    }
    let continuation = section
        .and_then(|s| arr(s, "continuations"))
        .and_then(|c| c.first())
        .and_then(Value::as_object)
        .and_then(|c| obj(c, "nextContinuationData"))
        .and_then(|n| string(n, "continuation"));
    HomePage { shelves, continuation }
}

