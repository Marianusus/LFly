/// The radio queue of a `/next` response (`playlistPanelVideoRenderer` items).
pub fn watch_next_tracks(root: &Value, limit: usize) -> Vec<Track> {
    let mut out = Vec::new();
    let mut seen = HashSet::new();
    for panel in collect(root, "playlistPanelVideoRenderer") {
        if out.len() >= limit {
            break;
        }
        let Some(video_id) = string(panel, "videoId").filter(|v| is_valid_video_id(v)) else { continue };
        if !seen.insert(video_id.clone()) {
            continue;
        }
        let title = runs_text(obj(panel, "title")).trim().to_string();
        if title.is_empty() {
            continue;
        }
        let short = obj(panel, "shortBylineText");
        let long = obj(panel, "longBylineText");
        let byline = some_nonblank(runs_text(short)).unwrap_or_else(|| runs_text(long));
        let byline_artist = byline.split('•').next().unwrap_or("").trim().to_string();
        let mut artists: Vec<ArtistCredit> = credits::from_runs(short);
        if artists.is_empty() {
            artists = credits::from_runs(long);
        }
        artists.retain(|c| !is_generic_artist(&c.name));
        let (artists, artist) = if artists.is_empty() {
            byline_artists(None, Some(&byline_artist), &title)
        } else {
            let name = credits::display_name(&artists);
            (artists, name)
        };
        let (mut album, mut album_id) = album_from_runs(short);
        if album.is_none() {
            (album, album_id) = album_from_runs(long);
        }
        out.push(Track {
            id: format!("yt_{video_id}"),
            title,
            artist,
            album,
            album_id,
            duration_ms: parse_duration_ms(&runs_text(obj(panel, "lengthText"))),
            cover_url: obj(panel, "thumbnail")
                .and_then(|t| arr(t, "thumbnails"))
                .and_then(|l| l.last())
                .and_then(Value::as_object)
                .and_then(|t| string(t, "url")),
            provider: "YouTube".to_string(),
            artist_id: credits::first_artist_id(&artists),
            artists: (!artists.is_empty()).then_some(artists),
            ..Track::default()
        });
    }
    out
}

