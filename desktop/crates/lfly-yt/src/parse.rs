/// Artists: id first, then normalized name.
pub fn merge_artists(primary: Vec<ArtistSummary>, secondary: Vec<ArtistSummary>, limit: usize) -> Vec<ArtistSummary> {
    let mut out = Vec::new();
    let mut ids = HashSet::new();
    let mut names = HashSet::new();
    for a in primary.into_iter().chain(secondary) {
        if out.len() >= limit {
            break;
        }
        let id = a.browse_id.clone().filter(|s| !s.is_empty()).or_else(|| a.channel_id.clone().filter(|s| !s.is_empty()));
        if let Some(id) = id {
            if !ids.insert(id) {
                continue;
            }
        }
        let key = normalized_name_key(&a.name);
        if !key.is_empty() && !names.insert(key) {
            continue;
        }
        out.push(a);
    }
    out
}

/// Albums: detail id first, then normalized title for id-less cards.
pub fn merge_albums(primary: Vec<AlbumSummary>, secondary: Vec<AlbumSummary>, limit: usize) -> Vec<AlbumSummary> {
    let mut out = Vec::new();
    let mut ids = HashSet::new();
    let mut keys = HashSet::new();
    for a in primary.into_iter().chain(secondary) {
        if out.len() >= limit {
            break;
        }
        let id = a.detail_id().map(str::to_string);
        if let Some(id) = &id {
            if !ids.insert(id.clone()) {
                continue;
            }
        }
        let key = normalized_name_key(&a.title);
        if id.is_none() && !key.is_empty() && !keys.insert(key.clone()) {
            continue;
        }
        if !key.is_empty() {
            keys.insert(key);
        }
        out.push(a);
    }
    out
}

/// Playlists: playlist id first, then normalized title for id-less cards.
pub fn merge_playlists(primary: Vec<PlaylistSummary>, secondary: Vec<PlaylistSummary>, limit: usize) -> Vec<PlaylistSummary> {
    let mut out = Vec::new();
    let mut ids = HashSet::new();
    let mut keys = HashSet::new();
    for p in primary.into_iter().chain(secondary) {
        if out.len() >= limit {
            break;
        }
        let id = p.detail_id().map(str::to_string);
        if let Some(id) = &id {
            if !ids.insert(id.clone()) {
                continue;
            }
        }
        let key = normalized_name_key(&p.title);
        if id.is_none() && !key.is_empty() && !keys.insert(key.clone()) {
            continue;
        }
        if !key.is_empty() {
            keys.insert(key);
        }
        out.push(p);
    }
    out
}

/// The active account in an `account/account_menu` response.
pub fn account_menu(root: &Value) -> Option<crate::AccountInfo> {
    let header = collect(root, "activeAccountHeaderRenderer").into_iter().next()?;
    let name = runs_text(obj(header, "accountName")).trim().to_string();
    if name.is_empty() {
        return None;
    }
    let simple = |key: &str| {
        obj(header, key)
            .map(|o| string(o, "simpleText").unwrap_or_else(|| runs_text(Some(o))))
            .unwrap_or_default()
    };
    let avatar_url = obj(header, "accountPhoto")
        .and_then(|p| arr(p, "thumbnails"))
        .and_then(|t| t.last())
        .and_then(Value::as_object)
        .and_then(|t| string(t, "url"));
    Some(crate::AccountInfo { name, handle: simple("channelHandle"), email: simple("email"), avatar_url })
}

